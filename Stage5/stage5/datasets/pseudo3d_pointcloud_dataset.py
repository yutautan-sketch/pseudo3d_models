from __future__ import annotations

from pathlib import Path
from typing import Any, Iterable

import numpy as np
import torch
from torch.utils.data import Dataset

from stage5.utils.feature_normalization import (
    normalize_frame_order,
    normalize_pixel_xy,
    normalize_uint8_feature,
    normalize_xyz,
)
from stage5.utils.h5_io import load_stage5_pointcloud_h5, read_path_list
from stage5.utils.point_sampling import PointSamplingConfig, sample_points


DEFAULT_FEATURES = ("intensity", "confidence")
SUPPORTED_FEATURES = (
    "intensity",
    "confidence",
    "alpha",
    "frame_order",
    "normalized_frame_order",
    "pixel_xy",
)


def read_h5_list(path: str | Path) -> list[Path]:
    return read_path_list(path)


def _coerce_paths(paths_or_list_file: str | Path | Iterable[str | Path]) -> list[Path]:
    if isinstance(paths_or_list_file, (str, Path)):
        path = Path(paths_or_list_file)
        if path.suffix.lower() in {".txt", ".lst", ".list"}:
            return read_path_list(path)
        return [path]
    return [Path(path) for path in paths_or_list_file]


def _parse_features(features: str | Iterable[str] | None) -> tuple[str, ...]:
    if features is None:
        return DEFAULT_FEATURES
    if isinstance(features, str):
        values = tuple(item.strip() for item in features.split(",") if item.strip())
    else:
        values = tuple(str(item).strip() for item in features if str(item).strip())
    unknown = [name for name in values if name not in SUPPORTED_FEATURES]
    if unknown:
        raise ValueError(
            f"Unsupported Stage5 feature(s): {unknown}. "
            f"Supported features are: {', '.join(SUPPORTED_FEATURES)}"
        )
    return values


class Pseudo3DPointCloudDataset(Dataset):
    """Dataset for weakly labeled pseudo-3D femur point-cloud segmentation.

    Each item corresponds to one annotated point-cloud H5 generated by
    Stage2to4/pseudo3d/annotation. The returned tensors are already sampled to
    a fixed number of points when ``num_points`` is set.
    """

    def __init__(
        self,
        h5_paths: str | Path | Iterable[str | Path],
        *,
        num_points: int | None = 8192,
        features: str | Iterable[str] | None = DEFAULT_FEATURES,
        normalize_points: bool = True,
        sampling_mode: str = "video",
        exclude_ignore_in_sampling: bool = False,
        positive_oversample_ratio: float = 0.0,
        frame_window_size: int | None = None,
        seed: int | None = None,
        cache_data: bool = False,
    ) -> None:
        self.h5_paths = _coerce_paths(h5_paths)
        if not self.h5_paths:
            raise ValueError("Pseudo3DPointCloudDataset received no H5 paths")

        self.num_points = num_points
        self.features = _parse_features(features)
        self.normalize_points = bool(normalize_points)
        self.sampling_config = PointSamplingConfig(
            mode=sampling_mode,
            num_points=num_points,
            exclude_ignore=bool(exclude_ignore_in_sampling),
            positive_oversample_ratio=float(positive_oversample_ratio),
            frame_window_size=frame_window_size,
        )
        self.seed = seed
        self.cache_data = bool(cache_data)
        self._cache: dict[int, dict[str, Any]] = {}

    def __len__(self) -> int:
        return len(self.h5_paths)

    @property
    def num_feature_channels(self) -> int:
        channels = 0
        for name in self.features:
            channels += 2 if name == "pixel_xy" else 1
        return channels

    def _rng_for_index(self, index: int) -> np.random.Generator:
        if self.seed is None:
            return np.random.default_rng()
        return np.random.default_rng(int(self.seed) + int(index))

    def _load(self, index: int) -> dict[str, Any]:
        if self.cache_data and index in self._cache:
            return self._cache[index]
        data = load_stage5_pointcloud_h5(self.h5_paths[index])
        if self.cache_data:
            self._cache[index] = data
        return data

    def _build_features(self, data: dict[str, Any]) -> np.ndarray:
        arrays: list[np.ndarray] = []
        for name in self.features:
            if name == "intensity":
                arrays.append(normalize_uint8_feature(data["intensity"])[:, None])
            elif name == "confidence":
                arrays.append(data["confidence"].astype(np.float32)[:, None])
            elif name == "alpha":
                arrays.append(normalize_uint8_feature(data["alpha"])[:, None])
            elif name == "frame_order":
                arrays.append(data["frame_order"].astype(np.float32)[:, None])
            elif name == "normalized_frame_order":
                arrays.append(normalize_frame_order(data["frame_order"])[:, None])
            elif name == "pixel_xy":
                arrays.append(normalize_pixel_xy(data["pixel_xy"]))
            else:
                raise ValueError(f"Unsupported feature: {name}")

        if not arrays:
            return np.zeros((data["points"].shape[0], 0), dtype=np.float32)
        return np.concatenate(arrays, axis=1).astype(np.float32)

    def __getitem__(self, index: int) -> dict[str, Any]:
        data = self._load(index)
        labels = data["point_label"].astype(np.int64)
        valid_mask = data["valid_mask"].astype(bool)
        rng = self._rng_for_index(index)
        sampled_indices = sample_points(
            labels,
            valid_mask,
            rng=rng,
            config=self.sampling_config,
            frame_order=data.get("frame_order"),
        )

        points = data["points"].astype(np.float32)
        features = self._build_features(data)
        if self.normalize_points:
            points = normalize_xyz(points)

        sampled_points = points[sampled_indices]
        sampled_features = features[sampled_indices]
        sampled_labels = labels[sampled_indices]
        sampled_valid_mask = valid_mask[sampled_indices]

        return {
            "points": torch.from_numpy(sampled_points).float(),
            "features": torch.from_numpy(sampled_features).float(),
            "labels": torch.from_numpy(sampled_labels).long(),
            "valid_mask": torch.from_numpy(sampled_valid_mask).bool(),
            "meta": {
                "h5_path": str(self.h5_paths[index]),
                "num_source_points": int(points.shape[0]),
                "sampled_indices": torch.from_numpy(sampled_indices).long(),
            },
        }
